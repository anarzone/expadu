#!/usr/bin/env node
/* Draws the Events street's fixed layers once, as images.

   The mock's street (prototype/dev/design/events-next/street-art.js,
   generated by its street-generator) is ~900 KB of inline SVG: 3,937
   nodes on a desktop, with grain filters and 1,500 leaves. The browser
   has to parse, style and paint all of it on every visit. Here each fixed
   part is drawn once, in Chromium (Playwright: the same engine the mock
   is tuned in), trimmed to what it covers and saved as WebP under
   public/events/street/. What the hour changes stays out of the pictures:

   - `image`: drawn as it is; the page sets only its opacity or brightness.
   - `mask`: a shape filled with one colour that follows the hour (the
     skylines). Saved as its alpha; the page fills it with the colour.
   - `tint`: a shape with a two-colour gradient that follows the hour (the
     clouds, the puddles). Saved in greys (the gradient from white to
     black, shape by shape); the page maps grey back to the two colours.

   What moves on its own (the mock's animation classes in street-art.css:
   stars twinkling, wings, smoke, flickering windows, ripples, pigeons,
   falling leaves, rain and its splashes) is drawn as separate pictures,
   `parts` of its layer, each at rest, so the page moves it with transform
   and opacity alone: the compositor's work, nothing repainted per frame.

   Run it after the mock's street changes:
       node tools/events-street/build.mjs
   It needs Playwright's Chromium (npx playwright install chromium) and
   cwebp (brew install webp). It writes the images and
   resources/js/components/events-street/street-layers.json. */

