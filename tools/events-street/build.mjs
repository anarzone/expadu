/* The plaster's fine grain is noise over the whole wall, and noise is
   what pictures compress worst: with it the wall was 103 KB, and a lower
   quality simply loses the grain. So the wall is drawn without it, and
   the grain becomes a small tile the page lays over the plaster with
   multiply: per pixel, what the grain did to the plaster's colour. */
function withoutGrain(markup, prefix) {
    const grain = markup.match(
        new RegExp(
            `<rect y="[\\d.]+" width="[\\d.]+" height="[\\d.]+" filter="url\\(#${prefix}grain\\)" opacity="([\\d.]+)"></rect>`,
        ),
    );

    if (!grain) {
        throw new Error(`no ${prefix} grain`);
    }

    const box = grain[0].match(
        /y="([\d.]+)" width="([\d.]+)" height="([\d.]+)"/,
    );

    return {
        wall:
            markup.slice(0, grain.index) +
            markup.slice(grain.index + grain[0].length),
        grain: {
            y: Number(box[1]),
            height: Number(box[3]),
            opacity: Number(grain[1]),
        },
    };
}
